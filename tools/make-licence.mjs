#!/usr/bin/env node
/**
 * Licence keypair generation and issuing.
 *
 * The private key never enters the repository. It is written once to
 * .licence-private.jwk, which is gitignored, and it is the only thing that
 * can mint a licence — back it up somewhere you would put a password, because
 * losing it means every future licence has to be issued under a new public
 * key, and rotating the public key invalidates the licences already sold.
 *
 *   node tools/make-licence.mjs --init
 *   node tools/make-licence.mjs --name="Ada Lovelace" --tier=pro
 *   node tools/make-licence.mjs --name="Ada Lovelace" --tier=pro --days=365
 *   node tools/make-licence.mjs --verify="<key>"
 */
import { writeFile, readFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { webcrypto as crypto } from 'node:crypto';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PRIVATE = join(ROOT, '.licence-private.jwk');
const PUBLIC_SOURCE = join(ROOT, 'src/core/licence-key.ts');

const args = process.argv.slice(2);
const flag = (name, dflt) => {
  const hit = args.find((a) => a === `--${name}` || a.startsWith(`--${name}=`));
  if (!hit) return dflt;
  const eq = hit.indexOf('=');
  return eq === -1 ? true : hit.slice(eq + 1);
};

const b64url = (bytes) =>
  Buffer.from(bytes).toString('base64').replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
const unb64url = (text) => Buffer.from(text.replace(/-/g, '+').replace(/_/g, '/'), 'base64');

async function init() {
  if (existsSync(PRIVATE) && !flag('force', false)) {
    console.error(
      `${PRIVATE} already exists.\n` +
        'Refusing to overwrite it: doing so would invalidate every licence already issued.\n' +
        'Pass --force if you genuinely mean to rotate the signing key.',
    );
    process.exit(1);
  }

  const pair = await crypto.subtle.generateKey(
    { name: 'ECDSA', namedCurve: 'P-256' },
    true,
    ['sign', 'verify'],
  );
  const privateJwk = await crypto.subtle.exportKey('jwk', pair.privateKey);
  const publicJwk = await crypto.subtle.exportKey('jwk', pair.publicKey);

  await writeFile(PRIVATE, JSON.stringify(privateJwk, null, 2) + '\n', { mode: 0o600 });

  // Only the public half goes into the source tree.
  const source = `/**
 * Licence signing public key.
 *
 * Generated by tools/make-licence.mjs --init. Only the public half lives
 * here; the private key is the thing that mints licences and it is not in
 * this repository.
 *
 * Rotating this key invalidates every licence already issued, so it is not a
 * thing to do casually.
 */
export const LICENCE_PUBLIC_KEY_JWK = ${JSON.stringify(
    { kty: publicJwk.kty, crv: publicJwk.crv, x: publicJwk.x, y: publicJwk.y, ext: true },
    null,
    2,
  )} as const;
`;
  await writeFile(PUBLIC_SOURCE, source);

  console.log(`private key -> ${PRIVATE}  (gitignored; back this up)`);
  console.log(`public key  -> ${PUBLIC_SOURCE}`);
}

async function loadPrivate() {
  if (!existsSync(PRIVATE)) {
    console.error(`No signing key. Run:  node tools/make-licence.mjs --init`);
    process.exit(1);
  }
  const jwk = JSON.parse(await readFile(PRIVATE, 'utf8'));
  return crypto.subtle.importKey('jwk', jwk, { name: 'ECDSA', namedCurve: 'P-256' }, false, ['sign']);
}

async function issue() {
  const name = String(flag('name', ''));
  const tier = String(flag('tier', 'pro'));
  const days = flag('days', null);
  if (!name) {
    console.error('--name is required, and is shown back to the customer in settings.');
    process.exit(1);
  }
  if (tier !== 'pro' && tier !== 'free') {
    console.error(`--tier must be pro or free, got ${tier}`);
    process.exit(1);
  }

  const key = await loadPrivate();
  const payload = {
    v: 1,
    id: b64url(crypto.getRandomValues(new Uint8Array(8))),
    tier,
    name,
    issued: Date.now(),
    ...(days ? { expires: Date.now() + Number(days) * 86_400_000 } : {}),
  };

  const payloadPart = b64url(Buffer.from(JSON.stringify(payload), 'utf8'));
  const signature = await crypto.subtle.sign(
    { name: 'ECDSA', hash: 'SHA-256' },
    key,
    Buffer.from(payloadPart, 'utf8'),
  );

  const licence = `WEFT-${payloadPart}.${b64url(signature)}`;
  console.log(licence);
  console.error(
    `\nissued: ${payload.tier} to "${payload.name}"` +
      (payload.expires ? `, expires ${new Date(payload.expires).toISOString().slice(0, 10)}` : ', lifetime') +
      `\nid: ${payload.id}`,
  );
}

async function verify(input) {
  const source = await readFile(PUBLIC_SOURCE, 'utf8');
  const match = source.match(/LICENCE_PUBLIC_KEY_JWK = (\{[\s\S]*?\}) as const/);
  if (!match) {
    console.error('Could not read the public key from source.');
    process.exit(1);
  }
  const jwk = JSON.parse(match[1]);
  const key = await crypto.subtle.importKey('jwk', jwk, { name: 'ECDSA', namedCurve: 'P-256' }, false, [
    'verify',
  ]);

  const clean = input.trim().replace(/^WEFT-/i, '').replace(/\s+/g, '');
  const dot = clean.indexOf('.');
  const payloadPart = clean.slice(0, dot);
  const ok = await crypto.subtle.verify(
    { name: 'ECDSA', hash: 'SHA-256' },
    key,
    unb64url(clean.slice(dot + 1)),
    Buffer.from(payloadPart, 'utf8'),
  );
  const payload = JSON.parse(unb64url(payloadPart).toString('utf8'));
  console.log(ok ? 'VALID' : 'INVALID', JSON.stringify(payload));
  if (!ok) process.exit(1);
}

if (flag('init', false)) await init();
else if (flag('verify', false)) await verify(String(flag('verify', '')));
else await issue();
